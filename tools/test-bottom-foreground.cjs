const fs = require('node:fs');
const assert = require('node:assert/strict');
const scene = JSON.parse(fs.readFileSync(require('node:path').join(__dirname, '../assets/Scenes/ZombieRoad.scene'), 'utf8'));
const node = name => scene.find(n => n.__type__ === 'cc.Node' && n._name === name);
const components = n => n._components.map(r => scene[r.__id__]);
const playing = node('Playing');
const foreground = node('BottomForeground');
assert.ok(foreground);
assert.equal(scene[foreground._parent.__id__], playing);
assert.equal(scene[playing._children[0].__id__], foreground);
assert.equal(foreground._active, true);
assert.equal(foreground._layer, node('GameUI')._layer);
assert.deepEqual(foreground._lscale, { __type__: 'cc.Vec3', x: 1, y: 1, z: 1 });
const parts = components(foreground);
assert.deepEqual(parts.map(c => c.__type__), ['cc.UITransform', 'cc.Sprite', 'cc.Widget']);
const transform = parts[0], sprite = parts[1], widget = parts[2];
assert.equal(transform._anchorPoint.y, 0);
assert.ok(transform._contentSize.height > 0);
assert.equal(sprite._spriteFrame, null);
assert.equal(sprite._sizeMode, 0);
assert.equal(sprite._type, 0);
assert.equal(widget._alignFlags, 44);
assert.equal(widget._alignMode, 2);
assert.equal(widget._left, 0);
assert.equal(widget._right, 0);
assert.equal(widget._bottom, 0);
assert.equal(scene[widget._target.__id__], playing);
const camera = components(node('HUDCamera')).find(c => c.__type__ === 'cc.Camera');
assert.ok(camera._priority > 0);
assert.ok(camera._visibility & foreground._layer);
assert.equal(camera._clearFlags & 1, 0);
for (const [width, height] of [[1280,720], [1920,1080], [2560,1080], [1024,768], [844,390]]) {
    const availableWidth = width / height > 1280 / 720 ? 720 * width / height : 1280;
    const availableHeight = width / height > 1280 / 720 ? 720 : 1280 * height / width;
    const left = -availableWidth / 2 + widget._left;
    const right = availableWidth / 2 - widget._right;
    const bottom = -availableHeight / 2 + widget._bottom;
    assert.equal(right - left, availableWidth);
    assert.equal(bottom, -availableHeight / 2);
}
const bootstrap = fs.readFileSync(require('node:path').join(__dirname, '../assets/Scripts/game/presentation/GameHud.ts'), 'utf8');
assert.ok(bootstrap.includes("this.gameLayer.active = ['playing', 'paused', 'result'].includes(flow.screen)"));
console.log('PASS bottom foreground: authored empty sprite, world/UI draw order, no input blockers, gameplay visibility, left/right/bottom anchors at five viewport sizes');
